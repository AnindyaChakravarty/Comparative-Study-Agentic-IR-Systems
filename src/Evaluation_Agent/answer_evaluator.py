import json
from pydantic import BaseModel


class AnswerEvaluation(BaseModel):
    faithfulness: float
    answer_relevance: float
    answer_correctness: float
    critical_failure: bool
    comment: str


SYSTEM_PROMPT = """
You are an Answer Evaluation Agent.

Your task is to evaluate the answer generated by an information retrieval
and question answering pipeline.

Evaluate the generated answer against:

1. the user's original information need
2. the retrieved evidence available to the answer generator
3. the reference (gold) answer from the benchmark dataset

Evaluate the following dimensions:

1. faithfulness

Are the claims made in the generated answer supported by the retrieved
evidence?

A high score means the answer does not introduce unsupported claims,
fabricate information, or contradict the evidence.

2. answer_relevance

Does the answer directly address the user's information need?

A high score means the answer answers the question directly, covers the
important parts of the request, and avoids unnecessary information.

3. answer_correctness

Does the generated answer correctly answer the user's question when
compared with the reference answer?

Use the gold answer as the primary reference for correctness. Consider
semantic equivalence rather than requiring identical wording.

The retrieved evidence may also be considered when determining whether
the generated answer is factually supported, but retrieval quality must
not replace comparison with the gold answer.

Do not penalize an answer merely because it contains additional wording
that is not present in the gold answer, provided that the additional
claims are relevant and supported by the retrieved evidence.

Do not assume that a claim is correct simply because it sounds plausible.

Do not use retrieval scores as evidence of factual correctness.

Scoring:

0.0 = completely inadequate
0.25 = mostly inadequate
0.5 = partially adequate
0.75 = mostly adequate
1.0 = fully adequate

Evaluate each dimension independently.

Important distinction:

* Faithfulness evaluates whether the answer is supported by the retrieved evidence.
* Answer relevance evaluates whether the answer addresses the question.
* Answer correctness evaluates whether the answer agrees with the benchmark
  reference answer and correctly answers the user's question.

Return ONLY valid JSON with exactly this structure:

{
"faithfulness": 0.0,
"answer_relevance": 0.0,
"answer_correctness": 0.0,
"critical_failure": false,
"comment": "Brief explanation of the evaluation."
}

Do not add any additional fields.

"""


def _build_prompt(query, gold_answer, evidence, answer):

    evaluate = f"""
    Evaluate the following generated answer.

    USER QUERY:
    {query}

    GOLD ANSWER:
    {gold_answer}

    RETRIEVED EVIDENCE:
    {json.dumps(evidence, indent=2, ensure_ascii=False)}

    GENERATED ANSWER:
    {answer}

    Remember:
    - Evaluate the generated answer, not the retrieval strategy.
    - Evaluate faithfulness against the supplied evidence.
    - Evaluate relevance against the user's information need.
    - Evaluate correctness against the gold answer.
    - Semantic equivalence is sufficient; identical wording is not required.
    - Use the evidence as supporting context when judging factual claims.
    - Do not use retrieval scores as evidence of correctness.
    - Return only the required JSON object.
    """

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT
        },
        {
            "role": "user",
            "content": evaluate
        }
    ]

    return messages


def evaluate_answer(query,gold_answer,evidence,answer,generate):

    messages = _build_prompt(query=query,gold_answer=gold_answer,evidence=evidence,answer=answer)
    hyperparameters = {
    "temperature": 0.1,
    "top_p": 0.9,
    "top_k": 40,
    "repetition_penalty": 1.05}
    response = generate(messages, hyperparameters=hyperparameters)

    try:
        evaluation = AnswerEvaluation.model_validate_json(
            response.content
        )

        return evaluation.model_dump()

    except Exception as e:
        return {
            "error": "Invalid evaluator response",
            "details": str(e),
            "raw_output": response.content
        }


def build_answer_evaluation_response_format():
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "answer_evaluation",
            "strict": True,
            "schema": AnswerEvaluation.model_json_schema()
        }
    }